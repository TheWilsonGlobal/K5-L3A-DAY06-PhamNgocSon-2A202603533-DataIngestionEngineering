"""Aggregate everything into results/summary.md (numbers only come from result files)."""
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import config as cfg  # noqa: E402


def main() -> None:
    R = cfg.RESULTS
    met = json.loads((R / "metrics.json").read_text(encoding="utf-8"))
    ing = json.loads((R / "ingest_stats.json").read_text(encoding="utf-8"))
    ana = json.loads((R / "analysis.json").read_text(encoding="utf-8"))
    qs = {q["id"]: q for q in (json.loads(x) for x in cfg.BENCHMARK.open(encoding="utf-8") if x.strip())}
    L = ["# Summary (generated by scripts/summary.py)\n", f"Run at {ing['run_at']} | model {ing['model']} ({ing['dimensions']} dims) | cost ${ing['cost_usd']}\n"]
    L.append("## Hit@1 / Evidence Hit@3\n\n| Strategy | Split | Hit@1 | Hit@3 | Chunks | Ingest s (embed+write) | Search s (22 q) |\n|---|---|---|---|---|---|---|")
    for s in "ABC":
        idx = "A" if s == "A" else "B"
        for sp in ("dev", "test", "all"):
            m = met["metrics"][f"{s}/{sp}"]
            L.append(f"| {s} | {sp} | {m['hit1']}/{m['n']} | {m['hit3']}/{m['n']} | {ing[idx]['chunks']} | "
                     f"{ing[idx]['ingest_seconds_total'] if s != 'C' else '0 (reuses B)'} | {met['search_seconds_22_queries'][s]} |")
    L.append("\n## Chunk statistics\n\n| Index | chunks | chars total | tokens (est.) | len min/median/p95/max | chunks > 128 tokens | re-ingest count before->after |\n|---|---|---|---|---|---|---|")
    for s in "AB":
        i, t = ing[s], ana["truncated_chunks"][s]
        L.append(f"| {s} | {i['chunks']} | {i['chars_total']} | {i['tokens_total_estimate']} | {i['len_min']}/{i['len_median']}/{i['len_p95']}/{i['len_max']} "
                 f"| {t['over_limit']}/{t['total']} | {i['reingest']['count_before']}->{i['reingest']['count_after']} |")
    coh = list(csv.DictReader((R / "audit/coherence.csv").open(encoding="utf-8")))
    meta = list(csv.DictReader((R / "audit/metadata.csv").open(encoding="utf-8")))
    gro = list(csv.DictReader((R / "audit/grounding.csv").open(encoding="utf-8")))
    L.append("\n## Manual audits\n\n| Strategy | Coherence mean /2 (n) | Metadata ok (n/N) | Filter compliance on filter questions | Grounding 0/1/2 counts, mean /2 |\n|---|---|---|---|---|")
    traces = {s: [json.loads(x) for x in (R / f"traces_{s}.jsonl").open(encoding="utf-8")] for s in "ABC"}
    for s in "ABC":
        cs = [int(r["score_0_2"]) for r in coh if r["strategy"] == s]
        ms = [r for r in meta if r["strategy"] == s]
        gs = [int(r["score_0_2"]) for r in gro if r["strategy"] == s]
        fq = [t for t in traces[s] if qs[t["question_id"]].get("filter")]
        okf = sum(all(h["section"] == qs[t["question_id"]]["filter"]["section"] for h in t["hits"]) for t in fq)
        ft = [t for t in fq if t["split"] == "test"]
        okt = sum(all(h["section"] == qs[t["question_id"]]["filter"]["section"] for h in t["hits"]) for t in ft)
        tag = "applied" if s == "C" else "NOT applied (passive)"
        L.append(f"| {s} | {sum(cs)/len(cs):.2f} ({len(cs)}) | {sum(int(r['ok']) for r in ms)}/{len(ms)} | "
                 f"all {okf}/{len(fq)}, test {okt}/{len(ft)} [{tag}] | {gs.count(0)}/{gs.count(1)}/{gs.count(2)}, {sum(gs)/len(gs):.2f} |")
    L.append("\n## Metadata errors\n")
    for r in meta:
        if r["ok"] == "0":
            L.append(f"- {r['strategy']} {r['qid']} rank{r['rank']} page {r['page']}: {r['errors']}")
    L.append("\n## Per-question outcome (hit@1/hit@3 as 1/0)\n\n| id | split | gold | A top3 | A | B top3 | B | C top3 | C |\n|---|---|---|---|---|---|---|---|---|")
    for r in ana["per_question"]:
        cells = [r["id"], r["split"], str(r["gold_page"])]
        for s in "ABC":
            x = r[s]
            cells += [str(x["top3_pages"]), f"{int(x['hit1'])}/{int(x['hit3'])}" + ("*" if x["split_evidence"] else "")]
        L.append("| " + " | ".join(cells) + " |")
    (R / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
